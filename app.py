"""
app.py – Streamlit front-end for QuizForge (automatic question generation from textbooks).
Run with:  streamlit run app.py
"""
import html

import streamlit as st
import torch

from qgen.extractor import extract_text
from qgen.generator import ALLOWED_COUNTS, DIFFICULTY_LEVELS, MODEL_OPTIONS, QuestionGenerator
from qgen.pipeline import generate_quiz

MAX_UPLOAD_MB = 5  # maximum accepted document size (also set in .streamlit/config.toml)

st.set_page_config(page_title="QuizForge – AI Question Generator", page_icon="📚", layout="wide")

# ------------------------------------------------------------------------------ styling
CSS = """
<style>
.hero {background: linear-gradient(120deg,#6366f1,#8b5cf6 55%,#ec4899); padding: 2rem 2.2rem;
       border-radius: 18px; color: #fff; margin-bottom: 1.4rem;}
.hero h1 {margin: 0; font-size: 2.2rem; color:#fff;}
.hero p {margin: .4rem 0 0; opacity: .92; font-size: 1.02rem;}
.q-card {background: rgba(127,127,127,.09); border-left: 5px solid #8b5cf6; border-radius: 12px;
         padding: 1rem 1.2rem; margin: .8rem 0 .2rem;}
.q-card .num {color:#8b5cf6; font-weight: 700; margin-right: .5rem;}
.chip {display:inline-block; background: linear-gradient(90deg,#6366f1,#8b5cf6); color:#fff;
       padding: .2rem .75rem; border-radius: 999px; margin: .35rem .35rem 0 0; font-size: .85rem;}
.stButton>button {border-radius: 10px; font-weight: 600;}
</style>
"""
st.markdown(CSS, unsafe_allow_html=True)


# ------------------------------------------------------------------------------ helpers
@st.cache_resource(show_spinner=False)
def load_generator(model_name: str) -> QuestionGenerator:
    """Load the Seq2Seq model once and reuse it across Streamlit reruns."""
    return QuestionGenerator(model_name)


def build_export_text(items, difficulty: str, with_keywords: bool) -> str:
    """Create a plain-text version of the quiz for the download button."""
    lines = [f"Generated questions (difficulty: {difficulty})", ""]
    for i, it in enumerate(items, 1):
        lines.append(f"{i}. {it.question}")
        if with_keywords:
            lines.append("   Keywords: " + ", ".join(it.keywords))
    return "\n".join(lines)


# ------------------------------------------------------------------------------ state
st.session_state.setdefault("items", [])
st.session_state.setdefault("show_keywords", False)
st.session_state.setdefault("difficulty", "mid")

# ------------------------------------------------------------------------------ sidebar
with st.sidebar:
    st.header("⚙️ Model")
    model_label = st.selectbox("Seq2Seq LLM", list(MODEL_OPTIONS), index=1)
    st.caption("The first run downloads the model weights from Hugging Face. "
               "Larger models give better questions but are slower.")
    mode = st.radio("Generation mode", ["Fast (greedy)", "Better quality (beam search, slower)"],
                    help="Beam search explores 4 candidates per word: usually nicer questions, roughly 2-4x slower.")
    num_beams = 1 if mode.startswith("Fast") else 4
    if torch.cuda.is_available():
        st.success(f"GPU detected: {torch.cuda.get_device_name(0)}")
    else:
        st.warning("No GPU detected – running on CPU, which is slow. Install a CUDA build of PyTorch "
                   "if you have an NVIDIA GPU, or choose Flan-T5 Small.")
    st.divider()
    st.markdown("**Pipeline**\n\n1. Extract text (PDF/DOCX)\n2. Split into passages\n"
                "3. Flan-T5 encoder–decoder writes questions\n4. TF-IDF keywords of each answer")

# ------------------------------------------------------------------------------ header
st.markdown("""<div class="hero"><h1>📚 QuizForge</h1>
<p>Upload a textbook, pick a difficulty and get exam-style questions generated by a Seq2Seq Transformer LLM.</p></div>""",
            unsafe_allow_html=True)

# ------------------------------------------------------------------------------ inputs
st.subheader("1 · Upload your textbook")
uploaded = st.file_uploader("PDF or Word file", type=["pdf", "docx"],
                            help=f"Maximum file size: {MAX_UPLOAD_MB} MB")
# Backstop check in case the app is launched without .streamlit/config.toml
if uploaded is not None and uploaded.size > MAX_UPLOAD_MB * 1024 * 1024:
    st.error(f"File is {uploaded.size / 1024 / 1024:.1f} MB. The limit is {MAX_UPLOAD_MB} MB.")
    uploaded = None

st.subheader("2 · Choose settings")
c1, c2 = st.columns(2)
with c1:
    difficulty = st.select_slider("Difficulty level", options=[d.capitalize() for d in DIFFICULTY_LEVELS],
                                  value="Mid", help="Low = recall · Mid = understanding · High = analysis")
with c2:
    num_q = st.select_slider("Number of questions (multiples of 5, max 30)", options=ALLOWED_COUNTS, value=10)

generate_clicked = st.button("✨ Generate questions", type="primary", disabled=uploaded is None)

# ------------------------------------------------------------------------------ generation
if generate_clicked and uploaded:
    try:
        with st.spinner("Reading document…"):
            text = extract_text(uploaded.name, uploaded.getvalue())
        with st.spinner("Loading model (first run downloads weights)…"):
            generator = load_generator(MODEL_OPTIONS[model_label])
        bar = st.progress(0.0, text="Generating questions…")
        items = generate_quiz(text, generator, difficulty.lower(), num_q, num_beams=num_beams,
                              progress_callback=lambda p: bar.progress(p, text=f"Generating questions… {int(p * 100)}%"))
        bar.empty()
        st.session_state.update(items=items, show_keywords=False, difficulty=difficulty)
        if len(items) < num_q:
            st.warning(f"Only {len(items)} unique questions could be generated from this document.")
    except Exception as exc:  # show a friendly error instead of a stack trace
        st.error(f"Could not generate questions: {exc}")

# ------------------------------------------------------------------------------ results
items = st.session_state["items"]
if items:
    st.subheader(f"3 · Your questions ({st.session_state['difficulty']} difficulty)")

    if not st.session_state["show_keywords"]:
        if st.button("🔑 Answer the questions (show keywords)"):
            st.session_state["show_keywords"] = True
            st.rerun()
    else:
        if st.button("🙈 Hide keywords"):
            st.session_state["show_keywords"] = False
            st.rerun()

    for i, it in enumerate(items, 1):
        st.markdown(f'<div class="q-card"><span class="num">Q{i}.</span>{html.escape(it.question)}</div>',
                    unsafe_allow_html=True)
        if st.session_state["show_keywords"]:
            chips = "".join(f'<span class="chip">{html.escape(k)}</span>' for k in it.keywords) \
                    or "<em>No keywords found</em>"
            st.markdown(chips, unsafe_allow_html=True)
            with st.expander("Answer & source sentence"):
                st.write(it.answer)
                if it.evidence and it.evidence != it.answer:
                    st.caption("Source: " + it.evidence)

    st.download_button("⬇️ Download questions (.txt)",
                       build_export_text(items, st.session_state["difficulty"], st.session_state["show_keywords"]),
                       file_name="questions.txt")
